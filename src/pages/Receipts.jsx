import { useEffect, useState } from "react";
import { ReceiptText, Search, Inbox, Printer, Users, Gift, Eye } from "lucide-react";
import { db } from "../config/firebase";
import Modal from "../components/Modal";

// Firestore reads timestamps back as Timestamp objects, which expose
// .toDate(). Wrapping one in new Date(...) would be an Invalid Date
// (Timestamp.valueOf() returns a comparison string, not ms), so all
// date fields go through here first — same rule as the app's
// config/receipt.js.
const toDate = (value) => {
  if (value && typeof value.toDate === "function") return value.toDate();
  return new Date(value);
};

const fmtDate = (value) => {
  if (!value) return "—";
  const d = toDate(value);
  return isNaN(d.getTime()) ? "—" : d.toLocaleDateString();
};

const fmtTime = (value) => {
  if (!value) return "";
  const d = toDate(value);
  return isNaN(d.getTime()) ? "" : d.toLocaleTimeString();
};

const timeOf = (value) => {
  if (!value) return 0;
  const t = toDate(value).getTime();
  return isNaN(t) ? 0 : t;
};

// Receipt numbers: RCP-<year>-<first 6 alphanumeric chars of the doc
// ID, uppercased>. New redemptions stamp `receiptNo` at write time;
// docs created before the receipt feature have no such field, so
// derive it here with the same rule the app uses (the app's
// config/receipt.js) — both sides always produce the same number.
const receiptNoFor = (docId, createdAt) => {
  const d = toDate(createdAt);
  const year = isNaN(d.getTime()) ? new Date().getFullYear() : d.getFullYear();
  const suffix = String(docId)
    .replace(/[^A-Za-z0-9]/g, "")
    .slice(0, 6)
    .toUpperCase();
  return `RCP-${year}-${suffix}`;
};

// Receipt text lands inside HTML for printing — resident and item
// names are user-supplied, so escape them before they touch markup.
const escapeHtml = (value) =>
  String(value == null ? "" : value).replace(
    /[&<>"']/g,
    (c) =>
      ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c])
  );

const buildReceiptHtml = (row) => {
  const rows = [
    ["Date", fmtDate(row.createdAt), ""],
    ["Time", fmtTime(row.createdAt) || "—", ""],
    ["Resident", row.userName, ""],
    ["Item", row.itemName, ""],
    ...(row.quantity > 1 ? [["Quantity", String(row.quantity), ""]] : []),
    ["Points spent", `-${row.pointsSpent} pts`, "red"],
    [
      "Balance after",
      row.balanceAfter == null ? "—" : `${row.balanceAfter} pts`,
      "green",
    ],
    ["Status", "REDEEMED", "green"],
  ];
  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8" />
<title>${escapeHtml(row.receiptNo)}</title>
<style>
  @page { margin: 24px; }
  * { box-sizing: border-box; }
  body {
    margin: 0;
    background: #fff;
    color: #222;
    font-family: -apple-system, "Segoe UI", Roboto, Helvetica, Arial, sans-serif;
  }
  .receipt {
    max-width: 560px;
    margin: 0 auto;
    border: 1px solid #e2e2e2;
    border-radius: 14px;
    overflow: hidden;
  }
  .band {
    background: #6B8E4E;
    color: #fff;
    padding: 24px;
    text-align: center;
  }
  .band .kicker {
    font-size: 13px;
    letter-spacing: 3px;
    text-transform: uppercase;
    opacity: 0.85;
  }
  .band .title { font-size: 20px; font-weight: 700; margin-top: 6px; }
  .band .no { font-size: 24px; font-weight: 700; margin-top: 10px; letter-spacing: 1px; }
  .body { padding: 18px 24px; }
  .row {
    display: flex;
    justify-content: space-between;
    gap: 16px;
    padding: 11px 0;
    border-bottom: 1px dashed #e6e6e6;
    font-size: 15px;
  }
  .row:last-child { border-bottom: none; }
  .k { color: #777; }
  .v { font-weight: 600; text-align: right; }
  .v.red { color: #E57373; }
  .v.green { color: #4CAF50; }
  .foot {
    background: #fafafa;
    border-top: 1px solid #ececec;
    padding: 14px 24px;
    font-size: 12px;
    color: #999;
    text-align: center;
  }
</style>
</head>
<body>
  <div class="receipt">
    <div class="band">
      <div class="kicker">BRGY BIN</div>
      <div class="title">Redemption Receipt</div>
      <div class="no">${escapeHtml(row.receiptNo)}</div>
    </div>
    <div class="body">
      ${rows
        .map(
          ([key, value, cls]) =>
            `<div class="row"><span class="k">${escapeHtml(key)}</span><span class="v ${cls}">${escapeHtml(value)}</span></div>`
        )
        .join("\n      ")}
    </div>
    <div class="foot">Generated by the BRGY BIN admin portal · Barangay waste management</div>
  </div>
</body>
</html>`;
};

function StatCard({ icon: Icon, color, value, label }) {
  return (
    <div className="stat-card">
      <div className="stat-icon" style={{ background: color + "22", color }}>
        <Icon size={24} />
      </div>
      <div className="stat-value">{value}</div>
      <div className="stat-label">{label}</div>
    </div>
  );
}

/**
 * Reward receipts: every redemption across the barangay, newest
 * first. Rows open a detail modal with a print button; the
 * resident app shares the same documents as PDFs.
 *
 * Static by design — no claim/status tracking. Older redemptions
 * predate `receiptNo`/`balanceAfter`, so the number is derived from
 * the doc ID and the balance renders as an em dash.
 */
export default function Receipts() {
  const [rows, setRows] = useState([]);
  const [loading, setLoading] = useState(true);
  const [query, setQuery] = useState("");
  const [selected, setSelected] = useState(null);

  useEffect(() => {
    let alive = true;
    (async () => {
      try {
        const snapshot = await db.collection("redemptions").get();
        if (!alive) return;
        const list = snapshot.docs.map((d) => {
          const r = d.data();
          return {
            id: d.id,
            userId: r.userId || "",
            userName: r.userName || "Unknown resident",
            itemName: r.itemName || "—",
            pointsSpent: typeof r.pointsSpent === "number" ? r.pointsSpent : 0,
            balanceAfter: typeof r.balanceAfter === "number" ? r.balanceAfter : null,
            // Old redemptions predate quantity — they were single-item.
            quantity:
              typeof r.quantity === "number" && r.quantity > 0 ? r.quantity : 1,
            receiptNo: r.receiptNo || receiptNoFor(d.id, r.createdAt),
            createdAt: r.createdAt,
          };
        });
        list.sort((a, b) => timeOf(b.createdAt) - timeOf(a.createdAt));
        setRows(list);
      } catch (error) {
        console.log("Error loading receipts:", error);
      } finally {
        if (alive) setLoading(false);
      }
    })();
    return () => {
      alive = false;
    };
  }, []);

  const term = query.trim().toLowerCase();
  const filtered = term
    ? rows.filter(
        (r) =>
          r.userName.toLowerCase().includes(term) ||
          r.itemName.toLowerCase().includes(term) ||
          r.receiptNo.toLowerCase().includes(term)
      )
    : rows;

  const totalPoints = rows.reduce((sum, r) => sum + r.pointsSpent, 0);
  const residents = new Set(rows.map((r) => r.userId).filter(Boolean)).size;

  // Print opens a small window holding just the receipt, so an
  // admin can print one without dumping the whole portal page.
  const printReceipt = (row) => {
    if (!row) return;
    const win = window.open("", "_blank");
    if (!win) {
      console.log("Popup blocked — cannot open the print view");
      return;
    }
    win.document.write(buildReceiptHtml(row));
    win.document.close();
    win.focus();
    setTimeout(() => win.print(), 250);
  };

  return (
    <div className="page">
      <div className="page-head">
        <div>
          <h2>Reward Receipts</h2>
          <p className="muted">
            Every reward redemption, with its receipt number and points spent.
          </p>
        </div>
      </div>

      <div className="stats-grid">
        <StatCard
          icon={ReceiptText}
          color="#6B8E4E"
          value={rows.length}
          label="Receipts issued"
        />
        <StatCard
          icon={Gift}
          color="#E57373"
          value={totalPoints}
          label="Points spent"
        />
        <StatCard
          icon={Users}
          color="#4A90E2"
          value={residents}
          label="Residents served"
        />
      </div>

      {loading ? (
        <div className="page-loading">
          <div className="spinner" />
        </div>
      ) : rows.length === 0 ? (
        <div className="card">
          <div className="empty">
            <Inbox size={40} />
            <p className="empty-title">No receipts yet</p>
            <p className="empty-sub">
              Receipts appear here as soon as residents redeem rewards.
            </p>
          </div>
        </div>
      ) : (
        <>
          <label className="field" style={{ maxWidth: 360 }}>
            <span>Search receipts</span>
            <input
              type="text"
              placeholder="Resident, item or RCP number"
              value={query}
              onChange={(e) => setQuery(e.target.value)}
            />
          </label>

          <section className="card">
            <div className="card-head">
              <h3>
                <ReceiptText size={18} /> Receipts ({filtered.length})
              </h3>
            </div>

            {filtered.length === 0 ? (
              <div className="empty">
                <Search size={40} />
                <p className="empty-title">No matching receipts</p>
                <p className="empty-sub">Try a resident name, item or RCP number.</p>
              </div>
            ) : (
              filtered.map((row) => (
                <div
                  className="list-row"
                  key={row.id}
                  role="button"
                  tabIndex={0}
                  style={{ cursor: "pointer" }}
                  onClick={() => setSelected(row)}
                  onKeyDown={(e) => {
                    if (e.key === "Enter" || e.key === " ") {
                      e.preventDefault();
                      setSelected(row);
                    }
                  }}
                >
                  <div className="list-icon gold">
                    <ReceiptText size={18} />
                  </div>
                  <div className="list-main">
                    <div className="list-title">{row.userName}</div>
                    <div className="list-sub">
                      <span style={{ fontWeight: 700, color: "#6B8E4E" }}>
                        {row.receiptNo}
                      </span>
                      <span>· {fmtDate(row.createdAt)}</span>
                      <span>
                        · {row.quantity > 1 ? `${row.quantity} × ` : ""}
                        {row.itemName}
                      </span>
                    </div>
                  </div>
                  <span className="badge badge-olive">-{row.pointsSpent} pts</span>
                  <button
                    className="btn btn-ghost btn-sm"
                    onClick={(e) => {
                      e.stopPropagation();
                      setSelected(row);
                    }}
                  >
                    <Eye size={15} /> View
                  </button>
                </div>
              ))
            )}
          </section>
        </>
      )}

      <Modal
        open={!!selected}
        title={selected?.receiptNo || "Receipt"}
        onClose={() => setSelected(null)}
        width={560}
        footer={
          <>
            <button className="btn btn-ghost" onClick={() => setSelected(null)}>
              Close
            </button>
            <button
              className="btn btn-primary"
              onClick={() => printReceipt(selected)}
            >
              <Printer size={16} /> Print
            </button>
          </>
        }
      >
        {selected && (
          <>
            <div className="detail-grid">
              <div className="detail">
                <span className="detail-label">Resident</span>
                <span className="detail-value">{selected.userName}</span>
              </div>
              <div className="detail">
                <span className="detail-label">Date</span>
                <span className="detail-value">
                  {fmtDate(selected.createdAt)} {fmtTime(selected.createdAt)}
                </span>
              </div>
              <div className="detail">
                <span className="detail-label">Item</span>
                <span className="detail-value">{selected.itemName}</span>
              </div>
              <div className="detail">
                <span className="detail-label">Quantity</span>
                <span className="detail-value">{selected.quantity}</span>
              </div>
              <div className="detail">
                <span className="detail-label">Points spent</span>
                <span className="detail-value">-{selected.pointsSpent} pts</span>
              </div>
              <div className="detail">
                <span className="detail-label">Balance after</span>
                <span className="detail-value">
                  {selected.balanceAfter == null
                    ? "—"
                    : `${selected.balanceAfter} pts`}
                </span>
              </div>
              <div className="detail">
                <span className="detail-label">Status</span>
                <span className="detail-value">
                  <span className="badge badge-green">redeemed</span>
                </span>
              </div>
            </div>
            <p className="muted" style={{ marginTop: 14, fontSize: 13 }}>
              Receipt {selected.receiptNo} · issued automatically at redemption
              time by the resident app.
            </p>
          </>
        )}
      </Modal>
    </div>
  );
}
